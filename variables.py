# Producten en prijzen
product_1 = "Laptop"
prijs_1 = 800
aantal_1 = 3

product_2 = "Muis"
prijs_2 = 20
aantal_2 = 10

product_3 = "Toetsenbord"
prijs_3 = 50
aantal_3 = 5

# Totale omzet berekenen
totale_omzet = (prijs_1 * aantal_1) + (prijs_2 * aantal_2) + (prijs_3 * aantal_3)

# Producten printen
print("Product:", product_1)
print("Prijs:", prijs_1)
print("Aantal verkocht:", aantal_1)

print("Product:", product_2)
print("Prijs:", prijs_2)
print("Aantal verkocht:", aantal_2)

print("Product:", product_3)
print("Prijs:", prijs_3)
print("Aantal verkocht:", aantal_3)

print("Totale omzet:", totale_omzet)
